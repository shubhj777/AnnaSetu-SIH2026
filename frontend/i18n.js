Object.keys(I18N_EXTRA).forEach(lang => {
  I18N_DATA[lang] = { ...(I18N_DATA[lang] || {}), ...I18N_EXTRA[lang] };
});

function getSavedLanguage() {
  return localStorage.getItem("kq_lang") || "hi";
}

function saveLanguage(lang) {
  localStorage.setItem("kq_lang", lang);
}

function t(key, lang = getSavedLanguage()) {
  return (I18N_DATA[lang] && I18N_DATA[lang][key]) || I18N_DATA.hi[key] || key;
}

function getKeyForRenderedValue(value) {
  const clean = value.trim();
  if (!clean) return null;
  for (const lang of Object.keys(I18N_DATA)) {
    const entry = Object.entries(I18N_DATA[lang]).find(([, translated]) => translated === clean);
    if (entry) return entry[0];
  }
  return null;
}

function localizeDynamicContent(root = document.body, lang = getSavedLanguage()) {
  const targetDict = I18N_DATA[lang] || I18N_DATA.hi;
  if (!root || !targetDict) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest("[data-no-i18n]")) return NodeFilter.FILTER_REJECT;
      return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });

  const valuesToKeys = [];
  Object.values(I18N_DATA).forEach(dict => {
    Object.entries(dict).forEach(([key, value]) => {
      if (typeof value === "string" && value.length > 2) valuesToKeys.push([value, key]);
    });
  });
  valuesToKeys.sort((a, b) => b[0].length - a[0].length);

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach(node => {
    const original = node.nodeValue;
    const trimmed = original.trim();
    const exactKey = getKeyForRenderedValue(trimmed);
    if (exactKey && targetDict[exactKey]) {
      node.nodeValue = original.replace(trimmed, targetDict[exactKey]);
      return;
    }

    let updated = original;
    valuesToKeys.forEach(([sourceValue, key]) => {
      const targetValue = targetDict[key];
      if (targetValue && sourceValue !== targetValue && updated.includes(sourceValue)) {
        updated = updated.split(sourceValue).join(targetValue);
      }
    });
    node.nodeValue = updated;
  });
}

function translateUI(lang) {
  const dict = I18N_DATA[lang] || I18N_DATA.hi;
  saveLanguage(lang);
  document.documentElement.lang = lang;
  
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if ((el.tagName === "INPUT" || el.tagName === "TEXTAREA") && el.hasAttribute("placeholder")) {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
  localizeDynamicContent(document.body, lang);
}
